def translate_to_chinese(text):
    """Translate English text to Chinese using the dictionary."""
    # Direct match
    if text in CAD_TERMS:
        return CAD_TERMS[text]
    
    # Try to translate format strings by translating the static parts
    import re
    # Find format specifiers
    fmt_matches = list(re.finditer(r'%[-+#0]*\d*(?:\.\d+)?(?:zu|ll?[du]|[sdifgxXuc])|%%', text))
    
    if not fmt_matches:
        # No format specifiers, try word-by-word
        words = text.split()
        translated_words = []
        for w in words:
            # Clean punctuation
            clean = w.strip('(),.[]{}')
            if clean in CAD_TERMS:
                translated_words.append(CAD_TERMS[clean])
            else:
                translated_words.append(w)
        return ' '.join(translated_words)
    
    # Has format specifiers - replace static parts
    result = text
    offset = 0
    for m in fmt_matches:
        start, end = m.span()
        # Translate text before this format specifier
        before = text[offset:start]
        if before:
            translated_before = translate_to_chinese(before)
            result = result[:start] + translated_before + result[end:]
            offset = start + len(translated_before)
        else:
            offset = end
    
    # Translate remaining text after last format specifier
    last_end = fmt_matches[-1].end() if fmt_matches else 0
    if last_end < len(text):
        remaining = text[last_end:]
        translated_remaining = translate_to_chinese(remaining)
        result = result[:last_end] + translated_remaining
    
    return result

def main():
    print(f"Total entries: {len(CAT)}")
    
    # Generate translations
    translated = {}
    missing = []
    
    for en, tr_dict in CAT:
        zh = translate_to_chinese(en)
        if zh and zh != en:
            translated[en] = zh
        else:
            missing.append(en)
    
    print(f"Translated: {len(translated)}")
    print(f"Missing: {len(missing)}")
    
    # Output Python code to add to i18n_catalogue.py
    print("\n# Add these to CAT entries as 7th argument:")
    for en, zh in sorted(translated.items()):
        # Escape for Python string
        zh_escaped = zh.replace('"', '\\"').replace("'", "\\'")
        print(f'    # E("{en}", ..., "{zh_escaped}")')
    
    if missing:
        print("\n# Missing translations (need manual work):")
        for en in missing[:50]:
            print(f'    # "{en}"')

